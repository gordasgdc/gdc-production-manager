let CURRENT_LANG = localStorage.getItem("gdc_lang") || "ro";

function t(key) {
  const dict = TRANSLATIONS[CURRENT_LANG] || TRANSLATIONS.ro;
  return dict[key] || TRANSLATIONS.ro[key] || key;
}

// t() with {placeholder} substitution, e.g. tf("notif_deadline_soon", {days: 3})
function tf(key, params) {
  let str = t(key);
  Object.keys(params || {}).forEach(k => {
    str = str.replace(new RegExp(`\\{${k}\\}`, "g"), params[k]);
  });
  return str;
}

function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  CURRENT_LANG = lang;
  localStorage.setItem("gdc_lang", lang);
}
